// Rewrites generated/ordersClient.js from the states declared in
// src/orderState.js. Run with `npm run generate` after changing the states.

import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { ORDER_STATES, TRANSITIONS } from '../src/orderState.js';

const TARGET = new URL('../generated/ordersClient.js', import.meta.url);

const list = ORDER_STATES.map((state) => `  '${state}',`).join('\n');
const transitions = ORDER_STATES.map(
  (state) => `  ${state}: [${TRANSITIONS[state].map((next) => `'${next}'`).join(', ')}],`,
).join('\n');

const contents = `// Generated by \`npm run generate\` from src/orderState.js.
// Do not hand-edit: this file is overwritten on the next run.

export const ORDER_STATES = Object.freeze([
${list}
]);

export const ORDER_TRANSITIONS = Object.freeze({
${transitions}
});

/** Throw unless \`value\` is a state the API accepts. */
export function assertOrderState(value) {
  if (!ORDER_STATES.includes(value)) {
    throw new TypeError(\`unknown order state: \${JSON.stringify(value)}\`);
  }
  return value;
}

/** GET /orders, optionally filtered by state. \`transport\` performs the call. */
export async function listOrders(transport, { state } = {}) {
  const query = state ? \`?state=\${encodeURIComponent(assertOrderState(state))}\` : '';
  return transport('GET', \`/orders\${query}\`);
}

/** PATCH /orders/:id, moving the order to \`state\`. */
export async function updateOrderState(transport, id, state) {
  return transport('PATCH', \`/orders/\${encodeURIComponent(id)}\`, {
    state: assertOrderState(state),
  });
}
`;

await mkdir(fileURLToPath(new URL('../generated/', import.meta.url)), { recursive: true });
await writeFile(fileURLToPath(TARGET), contents, 'utf8');
process.stdout.write(`wrote ${fileURLToPath(TARGET)}\n`);
